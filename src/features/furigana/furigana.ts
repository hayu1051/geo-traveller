/**
 * わざと表に載せていない漢字。1文字では読みが決まらないもの。
 *
 *   日 … 「日本」にほん /「8月13日」にち /「次の日」ひ
 *   月 … 「8月」がつ / 曜日の「月」げつ
 *   中 … 「街の中」なか /「サマータイム中」ちゅう
 *   分 … 「15分」ふん /「分かれる」わ
 *   火水木金土 … 曜日として出る。「火山」のように熟語では拾える
 *
 * 曜日と「日」「月」は小学1〜2年で習うので、読めなくて困る場面も少ない。
 * ここに挙げた字は、抜けではなく決めごととして扱う。
 */
export const UNLISTED_KANJI = ['日', '月', '中', '分', '火', '水', '木', '金', '土']

/** 漢字1文字ぶんの範囲。CJK 統合漢字 */
const KANJI = /[一-鿿]/

/** 読みを引く表 */
const READINGS = new Map(FURIGANA)

/*
 * 見出し語をつないだ正規表現。長い語から順に並べてあるので、
 * 「日本語」と「日本」が両方あっても長い方が先に取られる。
 *
 * 毎回作り直すと重いのでモジュールに1つだけ持つ。g 付きの正規表現は
 * lastIndex を覚えているため、使う前に必ず 0 に戻すこと。
 */
const PATTERN = new RegExp(
  [...READINGS.keys()].sort((a, b) => b.length - a.length).join('|'),
  'g',
)

/** 切り分けたひとかたまり。yomi が null ならふりがなを付けない */
export type Segment = {
  text: string
  yomi: string | null
}

/** 漢字のかたまりと、それ以外のかたまりに切る */
const KANJI_RUN = /[一-鿿]+|[^一-鿿]+/g

/**
 * 見出し語の読みを、漢字のかたまりごとに割りつける。
 *
 * 「同じ日の」に「おなじひの」をまるごと乗せると、はじめから読める
 * 「じ」「の」の上にまでふりがなが乗る。読めるものに読みが付いていると、
 * どれを読めばよいのか分からなくなるので、漢字の上にだけ乗せたい。
 *
 * 送りがなを手がかりにする。「同じ日の」は 漢字・じ・漢字・の の並びなので、
 * /^(.+?)じ(.+?)の$/ を「おなじひの」に当てると「おな」「ひ」が取れる。
 *
 *   同じ日の / おなじひの → 同(おな) じ 日(ひ) の
 *   分かれ   / わかれ     → 分(わ) かれ
 *   お金     / おかね     → お 金(かね)
 *
 * 送りがなが読みの中に出てこない語（当て字など）は分けようがないので、
 * これまでどおり全体に乗せる。
 */
function alignReading(word: string, yomi: string): Segment[] {
  const parts = word.match(KANJI_RUN)
  // 漢字だけ、またはかなだけの語。分ける必要が無い
  if (!parts || parts.length === 1) return [{ text: word, yomi }]

  const source = parts.map((part) => (KANJI.test(part) ? '(.+?)' : part)).join('')
  const matched = new RegExp(`^${source}$`).exec(yomi)
  if (!matched) return [{ text: word, yomi }]

  let group = 0
  return parts.map((part) =>
    KANJI.test(part) ? { text: part, yomi: matched[++group] ?? yomi } : { text: part, yomi: null },
  )
}

/*
 * 割りつけた結果。表は動かないので、読み込みのときに一度だけ作る。
 * 画面を描くたびに正規表現を組み立て直さないための置き場。
 */
const ALIGNED = new Map(
  [...READINGS].map(([word, yomi]) => [word, alignReading(word, yomi)] as const),
)

/*
 * その位置から見出し語が始まるかを調べるための正規表現。
 * y（sticky）を付けると lastIndex の位置ぴったりからしか探さない。
 */
const WORD_AT = new RegExp(PATTERN.source, 'y')

function startsWord(text: string, index: number): boolean {
  WORD_AT.lastIndex = index
  return WORD_AT.test(text)
}

/**
 * 1文字の見出し語を見送るかどうか。
 *
 * 「約」に「やく」を付ける表があると、「予約」の「約」まで拾ってしまう。
 * 熟語の一部を1文字だけ切り出すと、まず間違った読みになるので、
 * となりが漢字なら熟語の途中とみなして見送る。
 *
 * ただし「となりが漢字」だけで決めると、こんどは拾えるものまで落とす。
 *
 *   世界一高いビル … 「高」の前は「一」だが、それは「世界一」として拾い終えている
 *   昔東西に分かれる … 「昔」の後ろは「東」だが、そこから「東西」が始まる
 *
 * どちらも熟語を切ってはいない。前は「すでに拾った所までか」、
 * 後ろは「そこから別の見出し語が始まるか」で見分ける。
 */
function skipsSingle(text: string, start: number, matchedUpTo: number): boolean {
  // 直前がまだ拾われていない漢字なら、熟語の途中
  if (start > matchedUpTo) {
    const before = text[start - 1]
    if (before !== undefined && KANJI.test(before)) return true
  }

  const after = text[start + 1]
  if (after !== undefined && KANJI.test(after) && !startsWord(text, start + 1)) return true

  return false
}

/**
 * 文字列を、ふりがなを付ける部分とそのままの部分に切り分ける。
 *
 * 見つからなければ、まるごと 1 つのかたまりとして返す。
 * 呼び出し側は返ってきた並びをそのまま順に出せばよい。
 */
export function splitFurigana(text: string): Segment[] {
  // 時刻や数字のように漢字が1文字も無い文字列は、探すまでもない
  if (!KANJI.test(text)) return [{ text, yomi: null }]

  const segments: Segment[] = []
  let last = 0

  PATTERN.lastIndex = 0
  let match: RegExpExecArray | null
  while ((match = PATTERN.exec(text)) !== null) {
    const word = match[0]
    const start = match.index

    if (word.length === 1 && skipsSingle(text, start, last)) continue

    if (start > last) segments.push({ text: text.slice(last, start), yomi: null })
    // 送りがなの入った語は、漢字のところだけに分かれて返ってくる
    segments.push(...(ALIGNED.get(word) ?? [{ text: word, yomi: null }]))
    last = start + word.length
  }

  if (last < text.length) segments.push({ text: text.slice(last), yomi: null })
  return segments
}

/** 表に載っている見出し語。テストと、抜けを調べるために使う */
export function furiganaWords(): string[] {
  return [...READINGS.keys()]
}
